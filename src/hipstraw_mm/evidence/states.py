_BY_NAME = {name.casefold(): code for code, name in STATE_NAMES.items()}


def state_code(text: str) -> str | None:
    """`"TX"`, `"tx"`, or `"Texas"` -> `"TX"`; anything else -> None."""
    cleaned = " ".join(text.replace(".", "").split())
    if cleaned.upper() in STATE_NAMES:
        return cleaned.upper()
    return _BY_NAME.get(cleaned.casefold())
